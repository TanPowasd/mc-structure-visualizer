import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import {
  CACHE_DIR,
  SERVERS_DIR,
  downloadFile,
  fetchJson,
  loadConfig,
  resolveJava
} from './utils.mjs';

async function resolveModrinthJar(projectSlug, loader, mcVersion) {
  const url =
    `https://api.modrinth.com/v2/project/${encodeURIComponent(projectSlug)}/version` +
    `?loaders=${encodeURIComponent(JSON.stringify([loader]))}` +
    `&game_versions=${encodeURIComponent(JSON.stringify([mcVersion]))}`;

  const versions = await fetchJson(url);
  if (!Array.isArray(versions) || versions.length === 0) {
    throw new Error(`Modrinth: no version found for ${projectSlug} (${loader} ${mcVersion})`);
  }

  // Prefer release over beta/alpha if available
  const release = versions.find((v) => v.version_type === 'release') || versions[0];
  const file = release.files.find((f) => f.primary) || release.files[0];

  return {
    versionNumber: release.version_number,
    filename: file.filename,
    url: file.url,
    sha512: file.hashes?.sha512
  };
}

function buildServerProperties(profile) {
  // Note: MC 1.20.1 and 1.21.x both support flat generator-settings JSON
  const flatSettings = JSON.stringify({
    biome: 'minecraft:plains',
    layers: [
      { block: 'minecraft:bedrock', height: 1 },
      { block: 'minecraft:sandstone', height: 55 }
    ],
    structure_overrides: []
  }).replace(/:/g, '\\:');

  return [
    '# Generated by MC Structure Visualizer Environment Setup',
    `server-ip=${profile.host}`,
    `server-port=${profile.port}`,
    `enable-rcon=true`,
    `rcon.port=${profile.rconPort}`,
    `rcon.password=${profile.rconPassword}`,
    `broadcast-rcon-to-ops=true`,
    `gamemode=creative`,
    `force-gamemode=true`,
    `difficulty=peaceful`,
    `level-name=world`,
    `level-type=minecraft\\:flat`,
    `generator-settings=${flatSettings}`,
    `generate-structures=false`,
    `spawn-monsters=false`,
    `spawn-animals=false`,
    `spawn-npcs=false`,
    `spawn-protection=0`,
    `online-mode=false`,
    `enforce-secure-profile=false`,
    `view-distance=10`,
    `simulation-distance=10`,
    `sync-chunk-writes=false`,
    `max-tick-time=60000`,
    `motd=MC Structure Visualizer Test Server (${profile.mcVersion} ${profile.loader})`
  ].join('\n') + '\n';
}

async function setupServerProfile(profileName, profile, cfg) {
  console.log(`\n========================================`);
  console.log(`[Server] Provisioning profile: ${profileName}`);
  console.log(`========================================`);

  const serverDir = path.join(SERVERS_DIR, profileName);
  const modsDir = path.join(serverDir, 'mods');
  await fsp.mkdir(modsDir, { recursive: true });

  const javaBin = resolveJava(profile.javaKey);
  console.log(`  [java] ${javaBin}`);

  if (profile.loader === 'fabric') {
    const { loaderVersion, installerVersion } = cfg.fabric;
    const launcherUrl =
      `https://meta.fabricmc.net/v2/versions/loader/` +
      `${encodeURIComponent(profile.mcVersion)}/${loaderVersion}/${installerVersion}/server/jar`;

    const cachedLauncher = path.join(
      CACHE_DIR,
      profile.mcVersion,
      `fabric-server-${profile.mcVersion}-${loaderVersion}-${installerVersion}.jar`
    );
    await downloadFile(launcherUrl, cachedLauncher, {
      label: `Fabric Server Launcher (${profile.mcVersion})`
    });

    const targetJar = path.join(serverDir, 'fabric-server-launch.jar');
    await fsp.copyFile(cachedLauncher, targetJar);

    // Pre-seed official vanilla server.jar into .fabric/server/ if already cached from setup-assets
    const cachedVanillaServer = path.join(CACHE_DIR, profile.mcVersion, 'server.jar');
    if (fs.existsSync(cachedVanillaServer)) {
      const fabricInternalDir = path.join(serverDir, '.fabric', 'server');
      await fsp.mkdir(fabricInternalDir, { recursive: true });
      const destVanilla = path.join(fabricInternalDir, `${profile.mcVersion}-server.jar`);
      if (!fs.existsSync(destVanilla)) {
        await fsp.copyFile(cachedVanillaServer, destVanilla);
      }
    }
  }

  // Download configured mods (Fabric API, WorldEdit, Carpet)
  const installedMods = [];
  for (const modSlug of profile.mods || []) {
    const resolved = await resolveModrinthJar(modSlug, profile.loader, profile.mcVersion);
    const cacheModPath = path.join(
      CACHE_DIR,
      'server-mods',
      `${profile.mcVersion}-${profile.loader}`,
      resolved.filename
    );
    await downloadFile(resolved.url, cacheModPath, {
      sha512: resolved.sha512,
      label: `[${profileName}] ${resolved.filename}`
    });
    const destModPath = path.join(modsDir, resolved.filename);
    await fsp.copyFile(cacheModPath, destModPath);
    installedMods.push({ slug: modSlug, ...resolved });
  }

  // Write eula.txt & server.properties
  await fsp.writeFile(
    path.join(serverDir, 'eula.txt'),
    '# Local development & testing server — subject to Mojang EULA (https://aka.ms/MinecraftEULA)\neula=true\n'
  );
  await fsp.writeFile(
    path.join(serverDir, 'server.properties'),
    buildServerProperties(profile)
  );

  // Create WorldEdit schematics folder ready for live structure exchange
  const weSchemDir = path.join(serverDir, 'config', 'worldedit', 'schematics');
  await fsp.mkdir(weSchemDir, { recursive: true });

  // Write profile start.ps1
  const ps1 = [
    `$ErrorActionPreference = "Stop"`,
    `Set-Location $PSScriptRoot`,
    `Write-Host "Starting ${profileName} on ${profile.host}:${profile.port} (RCON ${profile.rconPort})..." -ForegroundColor Cyan`,
    `& "${javaBin}" -Xms${profile.memoryMin} -Xmx${profile.memoryMax} -jar fabric-server-launch.jar nogui`
  ].join('\r\n') + '\r\n';
  await fsp.writeFile(path.join(serverDir, 'start.ps1'), ps1);

  await fsp.writeFile(
    path.join(serverDir, 'profile-manifest.json'),
    JSON.stringify(
      {
        profileName,
        ...profile,
        javaBin,
        installedMods,
        schematicsDir: weSchemDir,
        provisionedAt: new Date().toISOString()
      },
      null,
      2
    )
  );

  console.log(
    `  [done] ${profileName} provisioned (${installedMods.map((m) => m.filename).join(', ')})`
  );
}

async function main() {
  const cfg = loadConfig();
  await fsp.mkdir(SERVERS_DIR, { recursive: true });
  await fsp.writeFile(path.join(SERVERS_DIR, '.gitkeep'), '');

  const requestedProfile = process.argv.find((a) => a.startsWith('--profile='))?.split('=')[1];

  for (const [name, profile] of Object.entries(cfg.serverProfiles)) {
    if (requestedProfile && name !== requestedProfile) continue;
    await setupServerProfile(name, profile, cfg);
  }
}

main().catch((err) => {
  console.error('[Server] Setup failed:', err);
  process.exit(1);
});
